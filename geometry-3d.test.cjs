const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const handlers={},svg={addEventListener:(type,fn)=>handlers[type]=fn,setPointerCapture(){},focus(){},clientHeight:480};
const host={hidden:true,querySelector:()=>svg};
const context={renderGeometry(){},renderCompass(){},window:{addEventListener(){}},$:()=>host,esc:x=>x,rp:x=>x,console};
vm.createContext(context);
vm.runInContext(fs.readFileSync('geometry-3d.js','utf8'),context);
vm.runInContext('cubeDraw=()=>{}',context);
const state={owner:'compass',host:'compass-chart',people:[],yaw:0,pitch:0,zoom:1};
context.cubeMount(state,'Test cube');
let prevented=0;
const event=(id,x,y)=>({pointerId:id,clientX:x,clientY:y,button:0,preventDefault(){prevented++;}});
handlers.pointerdown(event(1,100,100));
handlers.pointermove(event(1,120,110));
assert.equal(state.yaw,.18);assert.equal(state.pitch,.09);
handlers.pointerdown(event(2,220,110));
handlers.pointermove(event(2,270,110));
assert.equal(state.zoom,1.5);
assert.equal(state.yaw,.18,'Pinching must not rotate');
handlers.pointerup(event(2,270,110));
handlers.pointermove(event(1,130,110));
assert.equal(state.yaw,.27,'One-finger rotation resumes without jumping');
handlers.pointercancel(event(1,130,110));
assert.equal(state.drag,null);
handlers.wheel({deltaY:-150,deltaMode:0,preventDefault(){prevented++;}});
assert.ok(state.zoom>1.5&&state.zoom<=2.5);
handlers.dblclick();assert.equal(state.zoom,1);assert.equal(state.yaw,-.9);
handlers.keydown({key:'+',preventDefault(){prevented++;}});assert.equal(state.zoom,1.15);
handlers.keydown({key:'Home',preventDefault(){prevented++;}});assert.equal(state.zoom,1);
handlers.selectstart({preventDefault(){prevented++;}});assert.ok(prevented>=6);
console.log('3D gestures: drag, pinch, release, cancel, wheel, reset, keyboard and text-selection prevention passed.');
